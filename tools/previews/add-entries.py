def main(path):
    d = json.load(open(path))
    new = {x['id']: x for x in [art(e) for e in ART] + [look(e) for e in LOOKS]}
    entries = [x for x in d['entries'] if x['id'] not in new]
    for prefix, last in (('R', 'R36'), ('F', 'F08')):
        add = [v for k, v in new.items() if k[0] == prefix]
        at = max(i for i, x in enumerate(entries) if x['id'][0] == prefix) + 1
        entries[at:at] = add
    d['entries'] = entries
    json.dump(d, open(path, 'w'), ensure_ascii=True, separators=(',', ':'))
    print(len(ART), 'art styles,', len(LOOKS), 'film looks merged;', len(entries), 'entries')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'site/expansion.json')
