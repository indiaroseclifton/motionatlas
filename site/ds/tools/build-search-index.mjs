// Rebuilds ds/search-index.js from the h2/h3 headings (with ids) of every page in ds/.
// Run from the repo root: node site/ds/tools/build-search-index.mjs
import fs from 'fs';import path from 'path';import {fileURLToPath} from 'url';
const dir=path.join(path.dirname(fileURLToPath(import.meta.url)),'..');
const strip=s=>s.replace(/<[^>]+>/g,'').replace(/&amp;/g,'&').replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&nbsp;/g,' ').replace(/\s+/g,' ').trim();
const out=[];
for(const f of fs.readdirSync(dir).filter(f=>f.endsWith('.html')&&!f.startsWith('ex-')).sort()){
 let s=fs.readFileSync(path.join(dir,f),'utf8');
 s=s.replace(/<dialog[\s\S]*?<\/dialog>/g,'').replace(/<script[\s\S]*?<\/script>/g,'').replace(/<pre[\s\S]*?<\/pre>/g,'');
 const title=strip((s.match(/<title>([\s\S]*?)<\/title>/)||[])[1]||f).split(' · ')[0];
 const lead=strip((s.match(/<p class="ds-lede">([\s\S]*?)<\/p>/)||[])[1]||'');
 for(const m of s.matchAll(/<h([23])[^>]*\bid="([^"]+)"[^>]*>([\s\S]*?)<\/h\1>/g)){
  const t=strip(m[3]);if(!t)continue;
  const after=s.slice(m.index+m[0].length,m.index+m[0].length+600);const d=strip((after.match(/<p class="ds-lead">([\s\S]*?)<\/p>/)||[])[1]||'').slice(0,140);
  out.push({t,u:f+'#'+m[2],p:title,d:d||title,k:(m[1]==='2'?'section ':'')+lead.slice(0,80)});
 }
}
fs.writeFileSync(path.join(dir,'search-index.js'),'/* generated by ds/tools/build-search-index.mjs */\nwindow.DS_INDEX='+JSON.stringify(out)+';\n');
console.log(out.length,'entries');
